#!/usr/bin/env bash
# Seeds 3 Ignite clusters with identical sample data via sqlline (bundled in image).
set -euo pipefail

SQL=$(cat <<'EOSQL'
CREATE TABLE IF NOT EXISTS REGISTER (
    OBJECTID VARCHAR PRIMARY KEY,
    CCRQTM TIMESTAMP,
    CCOPENDATE DATE,
    CCCLOSEDATE DATE,
    CURRENCY VARCHAR,
    CCBALANCERECALCDATE DATE
) WITH "CACHE_NAME=REGISTER, VALUE_TYPE=Register";

DELETE FROM REGISTER;

INSERT INTO REGISTER (OBJECTID, CCRQTM, CCOPENDATE, CURRENCY, CCBALANCERECALCDATE)
VALUES ('R001', TIMESTAMP '2026-01-15 12:00:00', DATE '2020-01-01', 'RUB', DATE '2026-05-24');

INSERT INTO REGISTER (OBJECTID, CCRQTM, CCOPENDATE, CURRENCY, CCBALANCERECALCDATE)
VALUES ('R002', TIMESTAMP '2026-01-16 12:00:00', DATE '2021-06-01', 'USD', DATE '2026-05-24');

CREATE TABLE IF NOT EXISTS CURRENCY (
    OBJECTID VARCHAR PRIMARY KEY,
    CCEKSCODE VARCHAR,
    CCEXTCODE VARCHAR,
    CCNAME VARCHAR,
    CCALPHACODE VARCHAR,
    CCALPHANUMCODE VARCHAR
) WITH "CACHE_NAME=CURRENCY, VALUE_TYPE=Currency";

DELETE FROM CURRENCY;
INSERT INTO CURRENCY VALUES ('CUR_RUB', '810', '810', 'Российский рубль', 'RUB', '643');
INSERT INTO CURRENCY VALUES ('CUR_USD', '840', '840', 'Доллар США',     'USD', '840');

CREATE TABLE IF NOT EXISTS DAYBALANCES (
    REGISTER VARCHAR,
    CCOPERATIONDAY DATE,
    CCSTARTSUM DECIMAL(20,6),
    CCSTARTSUMNAT DECIMAL(20,6),
    CCDTSUM DECIMAL(20,6),
    CCDTSUMNAT DECIMAL(20,6),
    CCKTSUM DECIMAL(20,6),
    CCKTSUMNAT DECIMAL(20,6),
    CCDTCOUNT INT,
    CCKTCOUNT INT,
    CCFINISHSUM DECIMAL(20,6),
    CCFINISHSUMNAT DECIMAL(20,6),
    PRIMARY KEY (REGISTER, CCOPERATIONDAY)
) WITH "CACHE_NAME=DAY_BALANCES, VALUE_TYPE=DayBalances";

DELETE FROM DAYBALANCES;
INSERT INTO DAYBALANCES VALUES ('R001', DATE '2026-05-24', 1000.00, 1000.00, 200.00, 200.00, 500.00, 500.00, 3, 2, 1300.00, 1300.00);
INSERT INTO DAYBALANCES VALUES ('R002', DATE '2026-05-24', 500.00, 45000.00, 100.00, 9000.00, 0.00, 0.00, 1, 0, 400.00, 36000.00);

!quit
EOSQL
)

for c in ignite-1 ignite-2 ignite-3; do
    echo "=== Seeding $c ==="
    docker exec -i $c /opt/ignite/apache-ignite/bin/sqlline.sh \
        --url=jdbc:ignite:thin://127.0.0.1:10800 \
        --silent=true --outputformat=csv --showHeader=false \
        <<< "$SQL" 2>&1 | tail -3
done

echo ""
echo "Done. Try: curl -X POST http://localhost:8080/api/consistency/run"
